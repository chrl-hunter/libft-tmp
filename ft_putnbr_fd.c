#include "libft.h"

static void	putnbr(long nb, int fd)
{
	if (nb < 0)
	{
		ft_putchar_fd('-', fd);
		nb = -nb;
	}
	if (nb >= 10)
		putnbr(nb / 10, fd);
	ft_putchar_fd('0' + (nb % 10), fd);
}

void	ft_putnbr_fd(int n, int fd)
{
	putnbr((long)n, fd);
}
